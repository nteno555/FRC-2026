public class Autos {
    private DriveSubsystem drive;

    public Autos(DriveSubsystem drive) {
        this.drive = drive;
    }

    public Command Taxi() {
        Command auto = drive.driveRobotRelative(() -> new ChassisSpeeds(1, 0, 0))
                        .withTimeout(2.0)
                .andThen(drive.driveRobotRelative(() -> new ChassisSpeeds(0, 0, 0)));
        return auto;
    }
}
